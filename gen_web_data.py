"""
Generate the browser demo's data file from the CSV dataset.

Reads data/movies.csv (the same file recommend.py uses) and writes
web/movies-data.js, a JavaScript file with one MOVIES array.
Run this again whenever movies.csv changes:

    python gen_web_data.py
"""

import csv
import json
from pathlib import Path

HERE = Path(__file__).parent
CSV_FILE = HERE / "data" / "movies.csv"
OUT_FILE = HERE / "web" / "movies-data.js"


def main() -> None:
    with CSV_FILE.open(newline="", encoding="utf-8") as file:
        movies = [
            {
                "title": row["title"],
                "year": int(row["year"]),
                "genres": row["genres"],
                "keywords": row["keywords"],
            }
            for row in csv.DictReader(file)
        ]

    OUT_FILE.parent.mkdir(exist_ok=True)
    with OUT_FILE.open("w", encoding="utf-8") as file:
        file.write("// Generated by gen_web_data.py from data/movies.csv - do not edit by hand.\n")
        file.write("const MOVIES = ")
        json.dump(movies, file, indent=2, ensure_ascii=False)
        file.write(";\n")

    print(f"Wrote {len(movies)} movies to {OUT_FILE}")


if __name__ == "__main__":
    main()
